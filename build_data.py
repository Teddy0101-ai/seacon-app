# ══════════════ 出题质量：去偏与校验 ══════════════
# 背景：2026-08-12 实测发现，一个对航运一无所知的人只用两条应试规则
#   ——判断题一律选「错」、选择题一律选第二个——就能拿 82.6%，并通关全部 39 节。
# 那样的 App 测不出学习者会不会，还会让他以为自己会了，比不学更糟。
# 下面这段在打包时强制去偏，并把偏倚指标做成断言：偏了就打不出包。
import collections
_RNG = random.Random(20260812)

def debias(U):
    """打乱选项顺序，答案索引跟着走。
    跳过 num（选项是有序量级刻度，打乱会读不通）和 order（o 本身就是正确顺序）。"""
    for u in U:
        for l in u["L"]:
            for q in l["q"]:
                if q["k"] not in ("mc", "bank"):
                    continue
                idx = list(range(len(q["o"])))
                _RNG.shuffle(idx)
                q["o"] = [q["o"][i] for i in idx]
                q["a"] = idx.index(q["a"])

def audit(U):
    qs = [q for u in U for l in u["L"] for q in l["q"]]
    tf = [q for q in qs if q["k"] == "tf"]
    ch = [q for q in qs if q["k"] in ("mc", "bank", "num")]

    r_tf = sum(1 for q in tf if q["a"] == 0) / max(1, len(tf))
    hot = collections.Counter(q["a"] for q in ch)
    r_pos = max(hot.values()) / max(1, len(ch))
    # 「选最长的那个」是否也能当作弊规则——唯一最长才算线索
    def uniq_longest(q):
        ls = [len(o) for o in q["o"]]
        return ls[q["a"]] == max(ls) and ls.count(max(ls)) == 1
    r_len = sum(1 for q in ch if uniq_longest(q)) / max(1, len(ch))

    # 零知识模拟：判断题全选「错」，选择题全选最热索引，再叠一条「选最长」
    hot_i = hot.most_common(1)[0][0]
    def zero_knowledge(rule):
        ok = tot = 0
        for u in U:
            for l in u["L"]:
                for q in l["q"]:
                    if q["k"] == "tf":
                        tot += 1; ok += (q["a"] == 0)
                    elif q["k"] in ("mc", "bank", "num"):
                        tot += 1
                        pick = hot_i if rule == "pos" else max(
                            range(len(q["o"])), key=lambda i: len(q["o"][i]))
                        ok += (q["a"] == pick)
        return ok / max(1, tot)

    zk_pos, zk_len = zero_knowledge("pos"), zero_knowledge("len")
    print("  判断题偏「错」率      %5.1f%%   (目标 40—60)" % (r_tf * 100))
    print("  选择题最热索引占比    %5.1f%%   (目标 ≤ 40)" % (r_pos * 100))
    print("  正确项唯一最长占比    %5.1f%%   (目标 ≤ 45)" % (r_len * 100))
    print("  零知识命中·位置规则   %5.1f%%   (目标 ≤ 45)" % (zk_pos * 100))
    print("  零知识命中·长度规则   %5.1f%%   (目标 ≤ 50)" % (zk_len * 100))
    prod_n = sum(1 for q in qs if q["k"] == "prod")
    print("  产出题占比            %5.1f%%   (目标 ≥ 12)" % (prod_n / max(1, len(qs)) * 100))
    assert 0.40 <= r_tf <= 0.60, "判断题答案键偏倚 %.0f%%，先把题干改成正向表述再打包" % (r_tf * 100)
    assert r_pos <= 0.40, "选择题答案位置偏倚 %.0f%%" % (r_pos * 100)
    assert r_len <= 0.45, "正确项显著更长 %.0f%%，「选最长的」成了作弊通道——把干扰项写具体些" % (r_len * 100)
    assert zk_pos <= 0.45, "零知识·位置规则命中 %.0f%%，这个题库测不出学习者会不会" % (zk_pos * 100)
    assert zk_len <= 0.50, "零知识·长度规则命中 %.0f%%" % (zk_len * 100)
    assert prod_n / max(1, len(qs)) >= 0.12, "产出题太少 %d 道——全是选择题只能练「认得出」，练不出「说得出」" % prod_n

def stamp(U):
    """给每道题一个稳定 id。
    错题本原来存的是题目对象本身，用 === 比较——而 localStorage 存取会 JSON 往返，
    重载后拿到的是新对象，永远比不上，导致：跨会话答错同一题会不断堆积重复条目，
    复习答对也移不出错题本。改存 id 之后这个 bug 消失。
    末四位是题面哈希：题面改了 id 就变，旧的记忆记录自动失效而不会张冠李戴。"""
    import hashlib
    for u in U:
        for li, l in enumerate(u["L"]):
            for qi, q in enumerate(l["q"]):
                key = (q.get("q") or "") + "|" + "|".join(
                    x[0] for x in q.get("p", [])) + "|" + "|".join(q.get("o", []))
                q["id"] = "%s-%d-%d-%s" % (
                    u["id"], li, qi, hashlib.md5(key.encode("utf-8")).hexdigest()[:4])

debias(U)
stamp(U)
audit(U)

