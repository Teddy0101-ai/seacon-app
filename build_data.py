# ── 题型 ──────────────────────────────────────────────────
# tf   判断    q, a(1=对/0=错), why
# mc   选择    q, opts[], a(索引), why
# pair 配对    pairs[[左,右]...]
# bank 填空    q(用 ___ 占位), opts[], a(索引), why

U = []   # units

def unit(id, title, sub, color, icon, lessons):
    U.append({"id": id, "t": title, "s": sub, "c": color, "i": icon, "L": lessons})

def L(title, qs): return {"t": title, "q": qs}
def tf(q, a, why): return {"k": "tf", "q": q, "a": a, "w": why}
def mc(q, opts, a, why): return {"k": "mc", "q": q, "o": opts, "a": a, "w": why}
def pair(ps, tip=""): return {"k": "pair", "p": ps, "w": tip}
def bank(q, opts, a, why): return {"k": "bank", "q": q, "o": opts, "a": a, "w": why}
# num  数量级判断  —— 训练「这个数正常吗」的直觉，老手和新人的分水岭
def num(q, opts, a, why, pre=None):
    d = {"k": "num", "q": q, "o": opts, "a": a, "w": why}
    if pre: d["pre"] = pre
    return d
# order 排序      —— 训练流程顺序，按正确次序依次点击
def order(q, seq, why, pre=None):
    d = {"k": "order", "q": q, "o": seq, "w": why}
    if pre: d["pre"] = pre
    return d
# 给任意题挂一段情景前情，构成多步决策
def scene(txt, q):
    q = dict(q); q["pre"] = txt; return q
# prod 产出题 —— 不给选项，先自己说，再对参考要点，三档自评。
# 这是全库唯一训练「提取」而不是「再认」的题型：
# 再认只需要熟悉感，产出需要提取，两者是不同的记忆通路。
# 用再认题训练再用再认题测量，会稳定产生「学过、认得、但张不开嘴」。
def prod(q, points, why="", pre=None):
    d = {"k": "prod", "q": q, "m": points, "w": why}
    if pre: d["pre"] = pre
    return d

