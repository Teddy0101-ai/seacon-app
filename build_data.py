# ── 题型 ──────────────────────────────────────────────────
# tf   判断    q, a(1=对/0=错), why
# mc   选择    q, opts[], a(索引), why
# pair 配对    pairs[[左,右]...]
# bank 填空    q(用 ___ 占位), opts[], a(索引), why

U = []   # units

def unit(id, title, sub, color, icon, lessons):
    U.append({"id": id, "t": title, "s": sub, "c": color, "i": icon, "L": lessons})

def L(title, qs): return {"t": title, "q": qs}
def tf(q, a, why): return {"k": "tf", "q": q, "a": a, "w": why}
def mc(q, opts, a, why): return {"k": "mc", "q": q, "o": opts, "a": a, "w": why}
def pair(ps, tip=""): return {"k": "pair", "p": ps, "w": tip}
def bank(q, opts, a, why): return {"k": "bank", "q": q, "o": opts, "a": a, "w": why}

